#!/bin/sh
# plugin: sddm-textonly -- minimal text-only SDDM greeter for IPA hosts.
#
# Disables the graphical user list (no avatar fetching, no enumeration of
# IPA users on the login screen) and stops remembering the last user, so
# the greeter is a plain username/password prompt. Breeze stays current so
# KDE theming does not break.
#
# Sourced by freebsd-ipa-client.sh after the base configuration when
# requested:  sh freebsd-ipa-client.sh --plugins sddm-textonly
# Also runs directly:  sudo sh scripts/sddm-textonly.sh
# Uses the main script's log()/backup_file() when sourced, minimal
# built-ins below when run standalone. Honors DRY_RUN.
# SDDM_CONF may point elsewhere (the test suite does this).

# command -v is not enough: macOS ships /usr/bin/log, so require a shell
# function before assuming the main script's helpers are present.
if ! command -V log 2>/dev/null | grep -q 'function'; then
    log() { printf '%s\n' "$*"; }
fi
if ! command -V backup_file 2>/dev/null | grep -q 'function'; then
    backup_file() { # $1=file
        [ -e "$1" ] || return 0
        _bd="${BACKUP_DIR:-/var/backups/ipa-client}"
        mkdir -p "$_bd"
        cp -p "$1" "$_bd/$(echo "$1" | tr '/' '_').bak"
        log "backup: $1 -> $_bd/"
    }
fi

SDDM_CONF="${SDDM_CONF:-/usr/local/etc/sddm.conf.d/textonly.conf}"

log "plugin sddm-textonly: writing $SDDM_CONF"
if [ "${DRY_RUN:-no}" = "yes" ]; then
    log "[dry-run] write $SDDM_CONF"
else
    backup_file "$SDDM_CONF" || true
    mkdir -p "$(dirname "$SDDM_CONF")"
    cat > "$SDDM_CONF" <<'EOF'
# Generated by freebsd-ipa-client.sh (plugin sddm-textonly)
[Theme]
Current=breeze
EnableAvatars=false
DisableAvatarsThreshold=0

[Users]
MinimumUid=99999
MaximumUid=99999
RememberLastUser=false
EOF
    chmod 644 "$SDDM_CONF"
    log "wrote $SDDM_CONF (applies at next sddm start; re-login or reboot to pick it up)"
fi
